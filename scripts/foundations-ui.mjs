await page.getByRole('textbox',{name:'Base Size (px)',exact:true}).fill('32');
await page.getByRole('button',{name:'Generate icon scale'}).click();
await page.getByRole('combobox',{name:'Insert icon size'}).selectOption({label:'icon-size-md · 40px'});
await page.getByRole('button',{name:'Insert icon',exact:true}).click();
