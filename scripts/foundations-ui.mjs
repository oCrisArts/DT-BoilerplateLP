const generated=await page.evaluate(()=>window.__pluginRequests.findLast(m=>m.type==='generate-variables'));
assert.equal(generated.modules.length,4);assert.ok(generated.iconPreview.svg.includes('<svg'));assert.ok(!generated.tokens.some(t=>String(t.value).includes('<svg')));
