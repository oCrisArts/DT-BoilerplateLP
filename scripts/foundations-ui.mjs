const request=await page.evaluate(()=>window.__pluginRequests.findLast(m=>m.type==='insert-icon'));
assert.equal(request.size,40);assert.match(request.svg,/<svg/);assert.match(request.name,/Lucide \/ heart/);
await page.getByRole('combobox',{name:'Icon Library'}).selectOption('bootstrap-icons');
await page.getByRole('textbox',{name:'Base Size (px)',exact:true}).fill('16');
