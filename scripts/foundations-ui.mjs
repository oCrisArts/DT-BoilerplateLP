await page.getByRole('button',{name:/Inter.*quick brown/}).click();
await page.getByRole('button',{name:'Primary Font',exact:true}).filter({hasText:'Inter'}).waitFor();
await page.locator('[data-slot=popover-content]').waitFor({state:'hidden'});
await page.setViewportSize({width:420,height:1900});
await page.screenshot({path:output+'/plugin-typography.png',animations:'disabled'});
await page.getByRole('tab',{name:/Icons/}).click();
await page.getByRole('combobox',{name:'Icon Library'}).selectOption('lucide');
